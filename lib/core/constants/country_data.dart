  /// Sorted alphabetically by English name.
  static List<Country> get sorted {
    final List<Country> copy = List<Country>.from(all);
    copy.sort((a, b) => a.name.compareTo(b.name));
    return copy;
  }

  /// Filters on name, native name and dial code.
  static List<Country> search(String query) {
    final String q = query.trim().toLowerCase();
    if (q.isEmpty) return sorted;
    final String digits = q.replaceAll('+', '');
    return all.where((c) {
      return c.name.toLowerCase().contains(q) ||
          c.nativeName.toLowerCase().contains(q) ||
          c.iso.toLowerCase() == q ||
          (digits.isNotEmpty &&
              c.dialCode.replaceAll('+', '').startsWith(digits));
    }).toList()
      ..sort((a, b) => a.name.compareTo(b.name));
  }

  static Country? byIso(String iso) {
    for (final Country c in all) {
      if (c.iso.toUpperCase() == iso.toUpperCase()) return c;
    }
    return null;
  }

  static Country? byDialCode(String dialCode) {
    final String normalized = dialCode.replaceAll('+', '');
    for (final Country c in all) {
      if (c.dialCode.replaceAll('+', '') == normalized) return c;
    }
    return null;
  }
